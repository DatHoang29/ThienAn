import { defineStore } from 'pinia';

/**
 * Route List
 * @methods setRoutesList Sets the route data
 * @methods setColumnsMenuHover Sets the column layout menu mouse hover boolean
 * @methods setColumnsNavHover Sets the column layout leftmost navigation mouse hover boolean
 */
export const useRoutesList = defineStore('routesList', {
	state: (): RoutesListState => ({
		routesList: [],
		isColumnsMenuHover: false,
		isColumnsNavHover: false,
	}),
	actions: {
		async setRoutesList(data: Array<string>) {
			this.routesList = data;
		},
		async setColumnsMenuHover(bool: Boolean) {
			this.isColumnsMenuHover = bool;
		},
		async setColumnsNavHover(bool: Boolean) {
			this.isColumnsNavHover = bool;
		},
	},
});
